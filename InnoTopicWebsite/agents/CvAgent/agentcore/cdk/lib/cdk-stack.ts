import { AgentCoreApplication, type AgentCoreApplicationProps } from '@aws/agentcore-cdk';
import { RemovalPolicy, Stack, type StackProps } from 'aws-cdk-lib';
import * as iam from 'aws-cdk-lib/aws-iam';
import * as s3 from 'aws-cdk-lib/aws-s3';
import * as s3deploy from 'aws-cdk-lib/aws-s3-deployment';
import { AwsCustomResource, AwsCustomResourcePolicy, PhysicalResourceId } from 'aws-cdk-lib/custom-resources';
import { Construct } from 'constructs';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export interface AgentCoreStackProps extends StackProps {
  /** Props for the AgentCore application, produced by transformAgentCoreJson from agentcore/agentcore.json. */
  application: AgentCoreApplicationProps;
}

/**
 * The knowledge base's documents (agents/CvAgent/knowledge-base), generated by the website's
 * `pnpm knowledge-base`. The AgentCore CLI runs this CDK app from agentcore/cdk.
 */
const KNOWLEDGE_DOCUMENTS = join(process.cwd(), '../../knowledge-base');
/** Must match the bucket in agentcore.json's knowledge base data source URI. */
const KNOWLEDGE_BUCKET = 'innotopic-cv-agent-knowledge-736162636892';
const KNOWLEDGE_PREFIX = 'knowledge-base/';

/** A hash of every document, so an ingestion runs exactly when they change. */
function documentsHash(dir: string): string {
  const hash = createHash('sha256');
  const walk = (path: string) => {
    for (const entry of readdirSync(path, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = join(path, entry.name);
      if (entry.isDirectory()) walk(full);
      else hash.update(full.slice(dir.length)).update(readFileSync(full));
    }
  };
  walk(dir);
  return hash.digest('hex').slice(0, 16);
}

/**
 * The stack the AgentCore CLI deploys. Everything declared in agentcore/agentcore.json is
 * created by the AgentCoreApplication construct; below it, the resources it doesn't model:
 * the knowledge base's documents (bucket, upload, ingestion), and the agent's access to the
 * knowledge base and to the AgentCore Code Interpreter.
 */
export class AgentCoreStack extends Stack {
  public readonly application: AgentCoreApplication;

  constructor(scope: Construct, id: string, props: AgentCoreStackProps) {
    super(scope, id, props);
    this.application = new AgentCoreApplication(this, 'Application', props.application);
    const agent = this.application.runtime('agent');
    const knowledge = this.application.knowledgeBase('cvKnowledge');

    // The knowledge base's S3 data source: the bucket, with the documents uploaded on each deploy.
    const documents = new s3.Bucket(this, 'KnowledgeDocuments', {
      bucketName: KNOWLEDGE_BUCKET,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      encryption: s3.BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      removalPolicy: RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
    });
    knowledge.node.addDependency(documents);
    const upload = new s3deploy.BucketDeployment(this, 'UploadKnowledgeDocuments', {
      sources: [s3deploy.Source.asset(KNOWLEDGE_DOCUMENTS)],
      destinationBucket: documents,
      destinationKeyPrefix: KNOWLEDGE_PREFIX,
      prune: true,
    });

    // Index the documents: an ingestion job per data source, started again whenever they change.
    const version = documentsHash(KNOWLEDGE_DOCUMENTS);
    knowledge.dataSources.forEach((dataSource, index) => {
      const startIngestion = {
        service: 'bedrock-agent',
        action: 'StartIngestionJob',
        parameters: {
          knowledgeBaseId: knowledge.knowledgeBaseId,
          dataSourceId: dataSource.id,
          description: `Documents version ${version}`,
        },
        physicalResourceId: PhysicalResourceId.of(`ingestion-${version}`),
      };
      const ingestion = new AwsCustomResource(this, `IngestKnowledge${index}`, {
        onCreate: startIngestion,
        onUpdate: startIngestion,
        policy: AwsCustomResourcePolicy.fromStatements([
          new iam.PolicyStatement({ actions: ['bedrock:StartIngestionJob'], resources: [knowledge.knowledgeBaseArn] }),
        ]),
      });
      ingestion.node.addDependency(upload, knowledge);
    });

    // The agent retrieves from the knowledge base directly. (Once this CLI wires a project
    // knowledge base into a Gateway, it can become a Gateway tool like the work-history ones.)
    knowledge.grantRetrieve(agent);
    agent.addEnvironmentVariable('KNOWLEDGE_BASE_ID', knowledge.knowledgeBaseId);

    // The AgentCore Code Interpreter (AWS-managed), for calculations over the work history.
    agent.addToRolePolicy(new iam.PolicyStatement({
      actions: [
        'bedrock-agentcore:StartCodeInterpreterSession',
        'bedrock-agentcore:InvokeCodeInterpreter',
        'bedrock-agentcore:StopCodeInterpreterSession',
        'bedrock-agentcore:GetCodeInterpreterSession',
      ],
      resources: [`arn:${this.partition}:bedrock-agentcore:${this.region}:aws:code-interpreter/*`],
    }));
  }
}
