// Writes the app data the Vercel functions in api/ need, generated from the Angular app's TypeScript
// data modules:
// - api/_cv-context.ts: the CV page's data (personal data, skills, work history, books) as Markdown,
//   which the CV chat (api/cv-chat.ts) answers from;
// - api/_topic-categories.ts: every topic's name by category, which the semantic topic search
//   (api/topic-search.ts) picks from.
//   node scripts/generate-api-data.mjs
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))

/** Bundles a script entry with the app modules it imports, so Node can run it. */
async function load(entry) {
  const { outputFiles } = await build({
    entryPoints: [join(root, 'scripts', entry)],
    bundle: true,
    platform: 'node',
    format: 'esm',
    write: false,
    logLevel: 'warning',
  })
  return import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`)
}

function write(file, declaration, summary) {
  const output = join(root, 'api', file)
  writeFileSync(output, `// Generated by scripts/generate-api-data.mjs from the app data; do not edit.\n${declaration}\n`)
  console.log(`Wrote ${output} (${summary})`)
}

const { cvContext } = await load('cv-context.ts')
const markdown = cvContext()
write('_cv-context.ts', `export const CV_CONTEXT = ${JSON.stringify(markdown)};`, `${markdown.length} characters`)

const { topicCategories } = await load('topic-categories.ts')
const categories = topicCategories()
write('_topic-categories.ts',
  `export const TOPIC_CATEGORIES: { category: string; topics: string[] }[] = ${JSON.stringify(categories, null, 2)};`,
  `${categories.reduce((count, { topics }) => count + topics.length, 0)} topics`)
