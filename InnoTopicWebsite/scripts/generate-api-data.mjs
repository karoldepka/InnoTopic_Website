// Writes the CV page's data (personal data, skills, work history, books) as Markdown to
// api/_cv-context.ts, the context the CV chat (api/cv-chat.ts) answers from.
//   node scripts/generate-cv-context.mjs
import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const output = join(root, 'api/_cv-context.ts')

// The CV data lives in the Angular app's TypeScript modules; bundle them so Node can run them.
const { outputFiles } = await build({
  entryPoints: [join(root, 'scripts/cv-context.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
  logLevel: 'warning',
})
const { cvContext } = await import(`data:text/javascript;base64,${Buffer.from(outputFiles[0].text).toString('base64')}`)
const markdown = cvContext()

writeFileSync(output,
  '// Generated by scripts/generate-cv-context.mjs from the CV page data; do not edit.\n' +
  `export const CV_CONTEXT = ${JSON.stringify(markdown)};\n`)
console.log(`Wrote ${output} (${markdown.length} characters)`)
